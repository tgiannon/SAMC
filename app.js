let state=JSON.parse(localStorage.getItem("samcState")||'{"known":[],"missed":[],"seen":[]}');
function save(){localStorage.setItem("samcState",JSON.stringify(state))}
function showScreen(id){
 document.querySelectorAll(".screen").forEach(x=>x.classList.remove("active"));
 document.getElementById(id).classList.add("active");
 if(id==="study")renderCategories();
 if(id==="quiz")startQuiz();
 if(id==="board")startBoard();
 if(id==="progress")renderProgress();
 updateReadiness(); window.scrollTo(0,0);
}
function updateReadiness(){
 const total=questions.length;
 const known=state.known.length;
 document.getElementById("readiness").textContent=Math.round(known/total*100)+"%";
}
function renderCategories(){
 const cats=[...new Set(questions.map(x=>x.cat))];
 document.getElementById("categories").innerHTML=cats.map(c=>{
  const qs=questions.filter(x=>x.cat===c);
  return `<div class="topic"><b>${c}</b><span>${qs.length} questions</span><div class="source">${qs[0].src}</div></div>`;
 }).join("");
}
let quizIndex=0, quizQs=[];
function startQuiz(){
 const unseen=questions.filter(x=>!state.seen.includes(x.id));
 const pool=unseen.length?unseen:questions;
 quizQs=[...pool].sort(()=>Math.random()-.5).slice(0,20);
 quizIndex=0; renderQuiz();
}
function renderQuiz(){
 const box=document.getElementById("quizBox");
 if(quizIndex>=quizQs.length){
  box.innerHTML=`<div class="question"><div class="score">Done.</div><p>You completed ${quizQs.length} questions. Your progress is saved.</p><button class="btn" onclick="showScreen('progress')">View Progress</button></div>`;return;
 }
 const x=quizQs[quizIndex];
 state.seen=[...new Set([...state.seen,x.id])]; save();
 box.innerHTML=`<div class="question"><div class="muted">Question ${quizIndex+1} of ${quizQs.length} · ${x.cat}</div><h3>${x.q}</h3><div id="answer" style="display:none" class="answer"><b>Answer</b><br>${x.a}<div class="source">${x.src}</div></div><div class="btnrow"><button class="btn" onclick="document.getElementById('answer').style.display='block'">Reveal Answer</button><button class="btn alt" onclick="rate(${x.id},true)">✓ I knew it</button><button class="btn" onclick="rate(${x.id},false)">× Missed it</button></div></div>`;
}
function rate(id,known){
 state.known=state.known.filter(x=>x!==id); state.missed=state.missed.filter(x=>x!==id);
 (known?state.known:state.missed).push(id); save(); quizIndex++; renderQuiz(); updateReadiness();
}
let boardIndex=0, boardQs=[];
function startBoard(){
 boardQs=[...questions].sort(()=>Math.random()-.5).slice(0,15); boardIndex=0; renderBoard();
}
function renderBoard(){
 const box=document.getElementById("boardBox");
 if(boardIndex>=boardQs.length){
  box.innerHTML=`<div class="question"><div class="score">Board complete.</div><p>Review missed areas and repeat. A production version will add timed verbal answers, board-member roles, follow-ups, and chapter-specific scoring.</p><button class="btn" onclick="showScreen('progress')">View Progress</button></div>`;return;
 }
 const x=boardQs[boardIndex];
 box.innerHTML=`<div class="question"><div class="muted">Board Question ${boardIndex+1} of ${boardQs.length} · ${x.cat}</div><p class="boardprompt">${x.q}</p><p>Answer out loud before revealing the evaluation points.</p><div id="eval" style="display:none" class="answer"><b>Expected knowledge:</b><br>${x.a}<div class="source">${x.src}</div></div><div class="btnrow"><button class="btn" onclick="document.getElementById('eval').style.display='block'">Reveal Evaluation</button><button class="btn alt" onclick="boardRate(${x.id},true)">Strong answer</button><button class="btn" onclick="boardRate(${x.id},false)">Needs work</button></div></div>`;
}
function boardRate(id,strong){
 state.known=state.known.filter(x=>x!==id); state.missed=state.missed.filter(x=>x!==id);
 (strong?state.known:state.missed).push(id); save(); boardIndex++; renderBoard(); updateReadiness();
}
function renderProgress(){
 const total=questions.length, known=state.known.length, missed=state.missed.length;
 const pct=Math.round(known/total*100);
 const weak=questions.filter(x=>state.missed.includes(x.id));
 const cats={}; questions.forEach(x=>{cats[x.cat]=cats[x.cat]||{t:0,k:0};cats[x.cat].t++;if(state.known.includes(x.id))cats[x.cat].k++});
 const catHtml=Object.entries(cats).map(([c,v])=>`<div class="stat"><b>${c}</b><br>${Math.round(v.k/v.t*100)}% (${v.k}/${v.t})<div class="bar"><div class="fill" style="width:${Math.round(v.k/v.t*100)}%"></div></div></div>`).join("");
 document.getElementById("progressBox").innerHTML=`<div class="stat"><b>Overall readiness</b><div class="score">${pct}%</div><div class="bar"><div class="fill" style="width:${pct}%"></div></div></div><div class="stat"><b>Known</b><br>${known} questions</div><div class="stat"><b>Needs work</b><br>${missed} questions</div><h3>Category performance</h3>${catHtml}<div class="stat"><b>Recommended next</b><div class="checklist">${weak.length?weak.slice(0,12).map(x=>"• "+x.cat+": "+x.q).join("<br>"):"• Keep testing yourself across all categories."}</div></div>`;
}
